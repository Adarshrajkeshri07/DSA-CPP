// ==================== RECURSION ====================

// Recursion:
// Jab ek function khud ko hi call karta hai.

// Recursion ke 2 main parts:
// 1. Base Case      -> recursion ko stop karta hai
// 2. Recursive Case -> function khud ko dobara call karta hai

// Base Case nahi hoga -> Infinite Recursion -> Stack Overflow

// Recursion me problem ko chhote/simpler problem me break karte hain.

// Har recursive call Call Stack me store hoti hai.

// Example:
// factorial(5) = 5 * factorial(4)
// factorial(4) = 4 * factorial(3)
// ...
// factorial(1) = 1   <- Base Case

// Important:
// Base Case = STOP
// Recursive Case = REPEAT

